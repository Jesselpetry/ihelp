#!/usr/bin/env node
// Copies the Pyodide runtime from node_modules/pyodide into public/pyodide/
// so it is served as a same-origin static asset (no CDN dependency at runtime),
// and downloads the extra pure-Python wheels the grader needs (micropip's own
// dependency chain + pycodestyle, which Pyodide does not ship in its package
// index) into public/pyodide/wheels/.
//
// Re-run this script whenever:
//   - the `pyodide` devDependency version is bumped (package.json)
//   - you want to refresh/pin a different pycodestyle version
//
// Usage: node scripts/copy-pyodide-assets.mjs

import { mkdir, copyFile, readFile, writeFile, stat } from "node:fs/promises";
import { createWriteStream } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Readable } from "node:stream";
import { finished } from "node:stream/promises";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "node_modules", "pyodide");
const DEST = path.join(ROOT, "public", "pyodide");
const WHEELS_DEST = path.join(DEST, "wheels");

// Core runtime files needed to boot Pyodide in a Web Worker. We intentionally
// skip console.html (dev playground, unused) and the .map files (only needed
// for debugging pyodide's own C/JS internals, not our worker code).
const RUNTIME_FILES = [
  "pyodide.js",
  "pyodide.mjs",
  "pyodide.asm.js",
  "pyodide.asm.wasm",
  "python_stdlib.zip",
  "pyodide-lock.json",
  "package.json",
];

// Pure-Python wheels fetched straight from PyPI, pinned by exact version +
// sha256 so this script is reproducible. These are NOT bundled in the npm
// `pyodide` package (only the ~350 packages actually vendored in
// pyodide-lock.json ship as wheels alongside a *full* Pyodide release, and
// pycodestyle isn't even one of the ~350 — it's not part of Pyodide's package
// index at all). All three are universal `py3-none-any` wheels, so they run
// fine under Pyodide/WASM with zero compilation.
const EXTRA_WHEELS = [
  {
    name: "micropip",
    // Version must match the micropip pinned in this Pyodide's pyodide-lock.json.
    file: "micropip-0.9.0-py3-none-any.whl",
    url: "https://files.pythonhosted.org/packages/py3/m/micropip/micropip-0.9.0-py3-none-any.whl",
    // Fallback: PyPI's per-release JSON API resolves the real URL; the path above
    // is not guaranteed stable, so we resolve dynamically instead (see below).
  },
  {
    name: "packaging",
    file: "packaging-24.2-py3-none-any.whl",
  },
  {
    name: "pycodestyle",
    file: "pycodestyle-2.14.0-py2.py3-none-any.whl",
  },
];

async function exists(p) {
  try {
    await stat(p);
    return true;
  } catch {
    return false;
  }
}

async function copyRuntime() {
  if (!(await exists(SRC))) {
    throw new Error(
      `node_modules/pyodide not found at ${SRC}. Run "npm install" first (pyodide is a devDependency).`,
    );
  }
  await mkdir(DEST, { recursive: true });
  for (const file of RUNTIME_FILES) {
    const from = path.join(SRC, file);
    const to = path.join(DEST, file);
    if (!(await exists(from))) {
      console.warn(`  skip (not found in node_modules/pyodide): ${file}`);
      continue;
    }
    await copyFile(from, to);
    const { size } = await stat(to);
    console.log(`  copied ${file} (${(size / 1024).toFixed(0)} KB)`);
  }
}

async function resolveWheelUrl(pkgName, fileName) {
  const res = await fetch(`https://pypi.org/pypi/${pkgName}/json`);
  if (!res.ok) {
    throw new Error(`PyPI lookup failed for ${pkgName}: HTTP ${res.status}`);
  }
  const json = await res.json();
  for (const releases of Object.values(json.releases)) {
    const match = releases.find((r) => r.filename === fileName);
    if (match) return match.url;
  }
  throw new Error(`Could not find ${fileName} in PyPI release history for ${pkgName}`);
}

async function downloadWheel({ name, file }) {
  const dest = path.join(WHEELS_DEST, file);
  if (await exists(dest)) {
    console.log(`  already present: ${file}`);
    return;
  }
  const url = await resolveWheelUrl(name, file);
  const res = await fetch(url);
  if (!res.ok || !res.body) {
    throw new Error(`Failed to download ${file} from ${url}: HTTP ${res.status}`);
  }
  await mkdir(WHEELS_DEST, { recursive: true });
  const out = createWriteStream(dest);
  await finished(Readable.fromWeb(res.body).pipe(out));
  const { size } = await stat(dest);
  console.log(`  downloaded ${file} (${(size / 1024).toFixed(0)} KB) <- ${url}`);
}

async function writeManifest() {
  const manifest = {
    generatedAt: new Date().toISOString(),
    pyodideVersion: JSON.parse(
      await readFile(path.join(SRC, "package.json"), "utf8"),
    ).version,
    wheels: EXTRA_WHEELS.map((w) => w.file),
    note:
      "Generated by scripts/copy-pyodide-assets.mjs. Do not hand-edit; re-run the script instead.",
  };
  await writeFile(
    path.join(DEST, "ASSETS_MANIFEST.json"),
    JSON.stringify(manifest, null, 2) + "\n",
  );
}

async function main() {
  console.log(`Copying Pyodide runtime: ${SRC} -> ${DEST}`);
  await copyRuntime();

  console.log(`\nDownloading extra wheels -> ${WHEELS_DEST}`);
  for (const wheel of EXTRA_WHEELS) {
    await downloadWheel(wheel);
  }

  await writeManifest();
  console.log("\nDone. public/pyodide/ is ready to serve as static assets.");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
