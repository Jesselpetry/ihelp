""" สามเหลี่ยม """


def main():
    """สามเหลี่ยม"""
    n = int(input())

    for i in range(1, n + 1):
        if i in (1, n):
            # แถวแรกและแถวสุดท้ายเป็นขอบ ทึบทั้งแถว
            print("0" * i)
        else:
            # แถวกลางมีขอบซ้าย-ขวาเป็น 0 ตรงกลางกลวงเป็น 1
            print("0" + "1" * (i - 2) + "0")


if __name__ == "__main__":
    main()
