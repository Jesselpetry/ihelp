/**
 * The course list is generated from the catalog so the bot never points at a
 * course or URL that does not exist — adding a course to catalog.ts updates
 * the assistant too.
 */
function courseList(): string {
  return GROUPS.map((g) => {
    const lines = COURSES.filter((c) => c.group === g.id).map((c) => {
      const code = c.officialCode ? `${c.code} (${c.officialCode})` : c.code;
      const href = courseHref(c);
      return `  - ${code} ${c.nameTh} / ${c.nameEn}${href ? ` → ${href}` : ""}`;
    });
    return `- ${g.label.th}:\n${lines.join("\n")}`;
  }).join("\n");
}

