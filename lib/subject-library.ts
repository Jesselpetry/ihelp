/** "3.4 MB" / "812 KB" — the size line on a book-cover card. */
export function formatBytes(bytes: number): string {
  if (bytes >= 1024 * 1024) return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
  return `${Math.max(1, Math.round(bytes / 1024))} KB`;
}

/**
 * Stamps page counts and file sizes onto assets that point at a bundled file.
 * Call it in the server component; the numbers come from a build-time scan of
 * public/assets/ rather than from hand-written description strings, which go
 * stale the moment a PDF is swapped out.
 */
export function withAssetStats(assets: SubjectAsset[]): SubjectAsset[] {
  return assets.map((asset) => {
    const stat = STATS[asset.url.split("#")[0]];
    return stat ? { ...asset, pages: stat.pages, sizeBytes: stat.sizeBytes } : asset;
  });
}

