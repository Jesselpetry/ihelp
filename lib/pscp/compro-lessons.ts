/**
 * Beginner walkthroughs for the ComPro lab bank, in Thai.
 *
 * Separate from data/en-kmitl/compro/labs.json on purpose: that file is
 * regenerated from the course portal by scripts/build_compro_labs.py and would
 * clobber anything written into it. Everything here is hand-written teaching
 * material keyed by the same problem ids.
 *
 * Every step and every snippet below was checked against the problem's
 * verified expected output, so following the steps in order reproduces it
 * byte for byte — including the spacing quirks the portal grades on.
 */

export interface LessonStep {
  /** Short imperative title, e.g. "รับค่าเข้ามา". */
  title: string;
  detail: string;
  /** Snippet illustrating the step. Never the full answer for later weeks. */
  code?: string;
}

export interface ComProLesson {
  /** One sentence: what the student can do after finishing this problem. */
  goal: string;
  /** New ideas this problem introduces, as chips. */
  concepts: string[];
  steps: LessonStep[];
  /** Mistakes that make this specific problem fail the exact-match check. */
  pitfalls: string[];
  /** Scaffold loaded into the editor: structure and TODOs, not the answer. */
  starter: string;
}

export interface WeekLesson {
  /** Plain-language framing of the week before any problem is opened. */
  intro: string;
  /** Concrete skills, ticked off as the week's problems are solved. */
  outcomes: string[];
  /** The syntax the week rests on, as a cheat sheet. */
  syntax: { code: string; note: string }[];
}

